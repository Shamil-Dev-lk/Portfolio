ALTER TABLE public.portfolio_items ENABLE ROW LEVEL SECURITY;
CREATE POLICY "Anyone can view published portfolio items" ON public.portfolio_items FOR SELECT USING (status = 'PUBLISHED');
CREATE POLICY "Admins have full access to portfolio" ON public.portfolio_items USING (
